const dotDigits: Record<string, string[]> = {
  "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
  "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
  "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
  "3": ["11110", "00001", "00001", "01110", "00001", "00001", "11110"],
  "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
  "5": ["11111", "10000", "10000", "11110", "00001", "00001", "11110"],
  "6": ["01110", "10000", "10000", "11110", "10001", "10001", "01110"],
  "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
  "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
  "9": ["01110", "10001", "10001", "01111", "00001", "00001", "01110"],
  ":": ["0", "1", "1", "0", "1", "1", "0"]
};

const dotLetters: Record<string, string[]> = {
  C: ["111", "100", "100", "100", "111"],
  c: ["000", "111", "100", "100", "111"],
  L: ["100", "100", "100", "100", "111"],
  l: ["100", "100", "100", "100", "111"],
  A: ["111", "101", "111", "101", "101"],
  a: ["000", "000", "111", "101", "111"],
  U: ["101", "101", "101", "101", "111"],
  u: ["000", "000", "101", "101", "111"],
  D: ["110", "101", "101", "101", "110"],
  d: ["001", "001", "111", "101", "111"],
  I: ["111", "010", "010", "010", "111"],
  i: ["010", "000", "010", "010", "010"],
  O: ["111", "101", "101", "101", "111"],
  o: ["000", "000", "111", "101", "111"]
};

function DotChar({ char, isLabel }: { char: string; isLabel?: boolean }) {
  const map = isLabel ? dotLetters : dotDigits;
  const rows = map[char] ?? map["0"];
  if (!rows) return null;
  return (
    <span className={`dm-char${char === ":" ? " dm-char--colon" : ""}`}>
      {rows.map((row, ri) =>
        row.split("").map((cell, ci) => (
          <i className={`dm-dot${cell === "1" ? " dm-dot--on" : ""}`} key={`${ri}-${ci}`} />
        ))
      )}
    </span>
  );
}

export function DotMatrixClock({ value }: { value: string }) {
  return (
    <div className="dm-clock" aria-label={value}>
      {value.split("").map((c, i) => (
        <DotChar char={c} key={`${c}-${i}`} />
      ))}
    </div>
  );
}

export function DotMatrixLabel({ value }: { value: string }) {
  return (
    <span className="dm-label" aria-label={value}>
      {value.split("").map((c, i) => (
        <DotChar char={c} isLabel key={`${c}-${i}`} />
      ))}
    </span>
  );
}
